/* ---------------- 6. 解析：课程 → 教材 → 章节 ---------------- */
var _tbCache = {};
var _tbIndex = null;

function tbNorm(s) {
  return (s || '').replace(/[\s（）()·\/、，,：:．.]/g, '').toLowerCase();
}

function tbGet(key) {
  if (!key) return null;
  if (_tbCache[key]) return _tbCache[key];
  var raw = TEXTBOOK_LIB[key];
  if (!raw) return null;
  var chapters = (raw[4] || []).map(function (c, i) {
    if (typeof c === 'string') return { n: i + 1, t: c, p: [] };
    return { n: i + 1, t: c[0], p: (c[1] || []).slice() };
  });
  var o = {
    key: key,
    title: raw[0],
    author: raw[1],
    pub: raw[2],
    edition: raw[3] || '',
    chapters: chapters
  };
  _tbCache[key] = o;
  return o;
}

function tbIndex() {
  if (_tbIndex) return _tbIndex;
  _tbIndex = {};
  Object.keys(TEXTBOOK_LIB).forEach(function (k) {
    _tbIndex[tbNorm(k)] = k;
  });
  return _tbIndex;
}

/* 课程名 → 教材（先专业覆盖，再精确，再别名，再去符号模糊匹配） */
function textbookOf(majorId, courseName) {
  var ov = MAJOR_BOOK_OVERRIDES[majorId];
  if (ov && ov[courseName]) return tbGet(ov[courseName]);
  if (TEXTBOOK_LIB[courseName]) return tbGet(courseName);
  if (TEXTBOOK_ALIAS[courseName]) return tbGet(TEXTBOOK_ALIAS[courseName]);
  var idx = tbIndex();
  var hit = idx[tbNorm(courseName)];
  if (hit) return tbGet(hit);
  return null;
}

/* 专业培养方案 */
function schemeOf(majorId) {
  var s = MAJOR_SCHEMES[majorId];
  if (!s) return null;
  return { college: s[0], scheme: s[1], note: s[2] || '' };
}

/* 关卡名 → 章序号（"第 3 章"/"第 3 关" 优先，否则用下标） */
function chapterNoOf(levelName, index) {
  var m = /第\s*(\d+)\s*章/.exec(levelName || '');
  if (m) return parseInt(m[1], 10);
  var g = /第\s*(\d+)\s*关/.exec(levelName || '');
  if (g) return parseInt(g[1], 10);
  return (index || 0) + 1;
}

/* 关卡 → 同步教材信息（页面直接拿它渲染） */
function levelSyncOf(majorId, moduleName, levelName, index) {
  var sch = schemeOf(majorId);
  var book = textbookOf(majorId, moduleName);
  if (!sch && !book) return null;

  var n = chapterNoOf(levelName, index);
  var total = book ? book.chapters.length : 0;
  var ch = (total && n <= total) ? book.chapters[n - 1] : null;
  var diff = '入门';
  if (total) {
    if (n > Math.ceil(total * 2 / 3)) diff = '综合';
    else if (n > Math.ceil(total / 3)) diff = '进阶';
  }
  return {
    college: sch ? sch.college : '',
    scheme: sch ? sch.scheme : '',
    note: sch ? sch.note : '',
    book: book,
    chapterNo: n,
    chapterTitle: ch ? ch.t : '',
    points: ch ? ch.p : [],
    chapterTotal: total,
    difficulty: diff,
    inBook: !!ch
  };
}


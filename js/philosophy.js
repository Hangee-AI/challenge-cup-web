/* 把「模块表」注册成路径覆盖 + 文字说明
   - stageTitles：该专业四个阶段的标题（必须与 PATH_TEMPLATE 里的一致）
   - modules[i].stage：可选，指定该模块属于第几个阶段；
     不写时按「每阶段 3 个模块」自动分配（哲学 / 逻辑学就是这种）
   - 关卡 id 由模块序号生成：专业-m<序号>-l0 */
function registerMajorPath(majorId, stageTitles, modules, goals) {
  var override = {};
  stageTitles.forEach(function (t, i) {
    override[t] = { goal: goals[i], modules: [] };
  });
  modules.forEach(function (m, i) {
    var si = (typeof m.stage === 'number') ? m.stage : Math.floor(i / 3);
    var t = stageTitles[si];
    if (!override[t]) return;
    override[t].modules.push({
      name: m.name,
      levels: [{
        name: '第 ' + (i + 1) + ' 关 · ' + m.level,
        brief: m.brief,
        questions: m.q
      }]
    });
    DOCS[majorId + '-m' + i + '-l0'] = m.doc;
  });
  MAJOR_STAGE_OVERRIDES[majorId] = override;
}

/* 取某个门类模板的四个阶段标题（新专业复用门类阶段结构时用） */
function stageTitlesOf(cat) {
  return PATH_TEMPLATE[cat].stages.map(function (s) { return s.title; });
}

/* 给已注册专业的每门课追加章节（课程 → 章节）
   plan[课序号] = { name: 可选，改课程名, chapters: [{title, brief, q, doc}] }
   - 第 1 章沿用原来的课程导学，只把「第 N 关」改写成「第 1 章」
   - 追加的第 k 章会写成 DOCS['专业-m<课序号>-l<章序号>']，与 buildLevels 顺序一致 */
function addChapters(majorId, plan) {
  var override = MAJOR_STAGE_OVERRIDES[majorId];
  if (!override) return;
  var mi = 0;
  Object.keys(override).forEach(function (stageTitle) {
    override[stageTitle].modules.forEach(function (mod) {
      var i = mi++;
      var cfg = plan[i];
      if (!cfg) return;
      if (cfg.name) mod.name = cfg.name;
      var first = mod.levels[0];
      if (first) first.name = '第 1 章 · ' + first.name.replace(/^第\s*\d+\s*[关章]\s*·\s*/, '');
      (cfg.chapters || []).forEach(function (ch, k) {
        var n = k + 2;                        // 第 2 章、第 3 章……
        DOCS[majorId + '-m' + i + '-l' + (n - 1)] = ch.doc;
        mod.levels.push({
          name: '第 ' + n + ' 章 · ' + ch.title,
          brief: ch.brief,
          questions: ch.q,
          ready: true
        });
      });
    });
  });
}


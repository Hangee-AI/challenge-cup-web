/* 章节分组：标题形如「流程控制语句-03-if的第二种格式」，取第一个 '-' 前面当章节名 */
function bvSections() {
  var out = [];
  BV_CHAPTERS.forEach(function (ch, i) {
    var name = String(ch[0]).split('-')[0];
    var last = out[out.length - 1];
    if (!last || last.name !== name) {
      out.push({ name: name, from: i + 1, to: i + 1 });
    } else {
      last.to = i + 1;
    }
  });
  return out;
}


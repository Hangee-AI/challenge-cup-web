/* 高数类课程判定：模块名（课程名）里带这些关键词就用宋浩高数 */
var GAOSHU_NAME_RE = /高等数学|数学分析|微积分|高数/;

function isGaoshuModule(moduleName) {
  return GAOSHU_NAME_RE.test(String(moduleName || ''));
}

/* renderVideo 里调用：决定当前关卡用哪套视频课程 */
